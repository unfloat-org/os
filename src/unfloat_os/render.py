"""TRACKER.md: the generated dashboard in the records repository. Never edited by hand, never committed."""

from __future__ import annotations

import datetime as dt

from unfloat_os import schema, studies
from unfloat_os.records import Record, Records, Store, to_date
from unfloat_os.workspace import Workspace


def cell(value: object) -> str:
    return str(value or "").replace("|", "/").replace("\n", " ")


def link(record: Record) -> str:
    return f"[{record.id}](records/{record.kind.folder}/{record.path.name})"


def table(header: list[str], rows: list[list[str]]) -> list[str]:
    if not rows:
        return ["None.", ""]
    lines = ["| " + " | ".join(header) + " |", "|" + " --- |" * len(header)]
    lines += ["| " + " | ".join(cell(c) for c in row) + " |" for row in rows]
    return [*lines, ""]


def _owner_name(records: Records, record: Record) -> str:
    owner = schema.text(record.meta, "owner")
    if owner == "founder":
        return "Daniil"
    if owner == "claude":
        return "Claude"
    person = records.people.get(owner)
    return person.title if person else owner


def render_records(records: Records, today: dt.date, analyses: list[studies.Study] = ()) -> str:
    text = schema.text
    tasks = sorted(records.tasks.values(), key=lambda t: (text(t.meta, "due") or "9999-99-99", t.id))
    open_tasks = [t for t in tasks if t.meta.get("status") in schema.OPEN_STATUS]

    def task_row(t: Record, *extra: str) -> list[str]:
        return [f"{link(t)} {cell(t.title)}", text(t.meta, "due"), *extra]

    overdue = [t for t in open_tasks if (to_date(t.meta.get("due")) or dt.date.max) < today]
    active = [t for t in open_tasks if t.meta.get("status") in ("todo", "doing")]
    founder = [t for t in active if t.meta.get("owner") == "founder"]
    claude = [t for t in active if t.meta.get("owner") == "claude"]
    others = [t for t in active if t.meta.get("owner") not in schema.TASK_OWNERS]
    waiting = [t for t in open_tasks if t.meta.get("status") == "waiting"]

    out = [
        "# Tracker",
        "",
        f"Generated by `uo render` on {today.isoformat()}. Do not edit by hand: change the notes in `records/`, "
        "then render again.",
        "",
        f"Open tasks: {len(open_tasks)} (Daniil {len(founder)}, Claude {len(claude)}, others {len(others)}, "
        f"waiting {len(waiting)}). Overdue: {len(overdue)}.",
        "",
        "## Overdue",
        "",
        *table(
            ["Task", "Due", "Owner", "Status"],
            [task_row(t, _owner_name(records, t), text(t.meta, "status")) for t in overdue],
        ),
        "## Daniil: next actions",
        "",
        *table(
            ["Task", "Due", "Milestone", "Done when"],
            [task_row(t, text(t.meta, "milestone"), text(t.meta, "done_when")) for t in founder],
        ),
        "## Claude: queue",
        "",
        *table(
            ["Task", "Due", "Milestone", "Done when"],
            [task_row(t, text(t.meta, "milestone"), text(t.meta, "done_when")) for t in claude],
        ),
    ]
    if others:
        out += [
            "## Others",
            "",
            *table(["Task", "Due", "Owner"], [task_row(t, _owner_name(records, t)) for t in others]),
        ]
    out += [
        "## Waiting",
        "",
        *table(
            ["Task", "Due", "Owner", "Waiting on"],
            [task_row(t, _owner_name(records, t), text(t.meta, "waiting_on")) for t in waiting],
        ),
    ]

    pending = [
        d for d in sorted(records.drafts.values(), key=lambda d: d.id) if d.meta.get("status") in ("draft", "approved")
    ]
    out += [
        "## Drafts for Daniil",
        "",
        *table(
            ["Draft", "Status", "Channel", "Task"],
            [
                [f"{link(d)} {cell(d.title)}", text(d.meta, "status"), text(d.meta, "channel"), text(d.meta, "task")]
                for d in pending
            ],
        ),
    ]

    order = {status: index for index, status in enumerate(schema.PERSON_STATUS)}
    people = sorted(records.people.values(), key=lambda p: (order.get(text(p.meta, "status"), 99), p.id))
    out += [
        "## People",
        "",
        *table(
            ["Who", "Org", "Status", "Last contact", "Next task", "Milestones"],
            [
                [
                    f"{link(p)} {cell(p.title)}",
                    text(p.meta, "org"),
                    text(p.meta, "status"),
                    text(p.meta, "last_contact"),
                    text(p.meta, "next_task"),
                    ", ".join(schema.items(p.meta, "milestones")),
                ]
                for p in people
            ],
        ),
    ]

    if analyses:
        out += [
            "## Analyses",
            "",
            *table(
                ["Repository", "Analysis", "Status", "Verdict"],
                [
                    [a.repo, f"{a.id} {cell(text(a.meta, 'title'))}", text(a.meta, "status"), text(a.meta, "verdict")]
                    for a in analyses
                ],
            ),
        ]

    milestone_rows = []
    for milestone in schema.MILESTONES:
        in_milestone = [t for t in tasks if t.meta.get("milestone") == milestone]
        if in_milestone:
            milestone_rows.append(
                [
                    milestone,
                    str(sum(t.meta.get("status") in schema.OPEN_STATUS for t in in_milestone)),
                    str(sum(t.meta.get("status") == "done" for t in in_milestone)),
                ]
            )
    out += ["## Milestones and workstreams", "", *table(["Milestone", "Open", "Done"], milestone_rows)]

    recent = sorted(enumerate(records.events), key=lambda item: (item[1].date, item[0]), reverse=True)[:12]
    out += ["## Recent log", ""]
    out += [event.format() for _, event in recent] if recent else ["None."]
    out.append("")

    window = today - dt.timedelta(days=14)
    closed = [
        t
        for t in tasks
        if t.meta.get("status") in schema.CLOSED_STATUS and (to_date(t.meta.get("closed")) or dt.date.min) >= window
    ]
    out += [
        "## Closed in the last 14 days",
        "",
        *table(
            ["Task", "Closed", "Status"],
            [[f"{link(t)} {cell(t.title)}", text(t.meta, "closed"), text(t.meta, "status")] for t in closed],
        ),
    ]
    return "\n".join(out).rstrip() + "\n"


def render(ws: Workspace, today: dt.date) -> str:
    records = Store(ws.ops).load()
    analyses = [study for repo in ws.repos() for study in studies.load(repo)[0]]
    return render_records(records, today, analyses)
